#include <QRegularExpression>
#include <QVersionNumber>

namespace {

struct ParsedVersion
{
  QVersionNumber number;
  int stage = 3; // alpha < beta < rc < stable
  int stageNumber = 0;
};

bool parseVersion(const QString &text, ParsedVersion &version)
{
  // Accept release tags and the four-part version generated by CMake. Reject
  // partial numbers, unknown stages and trailing server/error text.
  static const QRegularExpression expression(
      QStringLiteral(
          "\\Av?([0-9]+(?:\\.[0-9]+){2,3})(?:-(stable|alpha[0-9]*|beta[0-9]*|rc[0-9]*))?"
          "(?:\\+[0-9A-Za-z.-]+)?\\z"
      ),
      QRegularExpression::CaseInsensitiveOption
  );
  const auto match = expression.match(text.trimmed());
  if (!match.hasMatch())
    return false;

  QList<int> segments;
  for (const auto &part : match.captured(1).split('.')) {
    bool ok = false;
    const int number = part.toInt(&ok);
    if (!ok)
      return false;
    segments.append(number);
  }
  version.number = QVersionNumber(segments).normalized();

  const auto stage = match.captured(2).toLower();
  if (stage.isEmpty() || stage == QStringLiteral("stable"))
    return true;

  const QString prefix = stage.startsWith(QStringLiteral("rc"))     ? QStringLiteral("rc")
                         : stage.startsWith(QStringLiteral("beta")) ? QStringLiteral("beta")
                                                                    : QStringLiteral("alpha");
  version.stage = prefix == QStringLiteral("rc") ? 2 : prefix == QStringLiteral("beta") ? 1 : 0;
  const auto ordinal = stage.mid(prefix.size());
  if (!ordinal.isEmpty()) {
    bool ok = false;
    version.stageNumber = ordinal.toInt(&ok);
    if (!ok)
      return false;
  }
  return true;
}

QString releaseVersion(const QByteArray &body)
{
  auto version = QString::fromUtf8(body).trimmed();
  if (version.startsWith('{') || version.startsWith('[')) {
    QJsonParseError error;
    const auto document = QJsonDocument::fromJson(body, &error);
    if (error.error != QJsonParseError::NoError || !document.isObject())
      return {};

    const auto release = document.object();
    for (const auto &flag : {QStringLiteral("draft"), QStringLiteral("prerelease")}) {
      const auto value = release.value(flag);
      if (!value.isUndefined() && (!value.isBool() || value.toBool()))
        return {};
    }
    if (!release.value(QStringLiteral("tag_name")).isString())
      return {};
    version = release.value(QStringLiteral("tag_name")).toString().trimmed();
  }

  ParsedVersion parsed;
  if (!parseVersion(version, parsed))
    return {};
  if (version.startsWith('v', Qt::CaseInsensitive))
    version.remove(0, 1);
  return version;
}

} // namespace

VersionChecker::VersionChecker(QObject *parent) : QObject(parent), m_network{new QNetworkAccessManager(this)}
{
  connect(m_network, &QNetworkAccessManager::finished, this, &VersionChecker::replyFinished, Qt::UniqueConnection);
}

void VersionChecker::checkLatest() const
{
  const QString url = Settings::value(Settings::Gui::UpdateCheckUrl).toString();
  qDebug("checking for updates at: %s", qPrintable(url));
  auto request = QNetworkRequest(url);
  auto userAgent = QString("%1 %2 on %3").arg(kAppName, kVersion, QSysInfo::prettyProductName());
  request.setHeader(QNetworkRequest::UserAgentHeader, userAgent);
  request.setRawHeader("X-Deskflow-Version", kVersion);
  request.setRawHeader("X-Deskflow-Language", qPrintable(QLocale::system().name()));
  request.setRawHeader("Accept", "application/vnd.github+json");
  request.setTransferTimeout(15000);
  m_network->get(request);
}

void VersionChecker::replyFinished(QNetworkReply *reply)
{
  // QNetworkAccessManager does not delete replies for us, including HTTP errors.
  reply->deleteLater();
  const auto httpStatus = reply->attribute(QNetworkRequest::HttpStatusCodeAttribute).toInt();
  if (reply->error() != QNetworkReply::NoError || httpStatus < 200 || httpStatus >= 300) {
    qWarning("version check server error: %s", qPrintable(reply->errorString()));
    qWarning("error checking for updates, http status: %d", httpStatus);
    return;
  }

  qDebug("version check server success, http status: %d", httpStatus);

  const auto newestVersion = releaseVersion(reply->readAll());

  if (newestVersion.isEmpty()) {
    qWarning() << "version check response contains no valid published release version";
    return;
  }

  if (compareVersions(kVersion, newestVersion) > 0) {
    qWarning().noquote() //
        << QStringLiteral("current version %1 out of date, update available: %2").arg(kVersion, newestVersion);
    Q_EMIT updateFound(newestVersion);
  } else {
    qDebug().noquote() << QStringLiteral("current version %1 is upto date").arg(kVersion);
  }
}

int VersionChecker::compareVersions(const QString &left, const QString &right)
{
  ParsedVersion current;
  ParsedVersion available;
  if (!parseVersion(left, current) || !parseVersion(right, available))
    return 0;

  const int numberOrder = QVersionNumber::compare(current.number, available.number);
  if (numberOrder != 0)
    return numberOrder < 0 ? 1 : -1;
  if (current.stage != available.stage)
    return current.stage < available.stage ? 1 : -1;
  if (current.stageNumber != available.stageNumber)
    return current.stageNumber < available.stageNumber ? 1 : -1;
  return 0;
}
